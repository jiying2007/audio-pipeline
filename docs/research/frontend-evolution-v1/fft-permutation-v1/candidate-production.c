float ap_clampf(float x, float lo, float hi) {
    return x < lo ? lo : (x > hi ? hi : x);
}

float ap_rms_dbfs(const float *x, uint32_t n) {
    float e = 1.0e-18f;
    uint32_t i;
    for (i = 0u; i < n; ++i) e += x[i] * x[i];
    e /= n ? (float)n : 1.0f;
    return 10.0f * log10f(e);
}

