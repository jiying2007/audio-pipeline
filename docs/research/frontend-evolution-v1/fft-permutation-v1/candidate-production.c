void ap_fft(ap_complex_t *x, uint32_t n, int inverse) {
    uint32_t i, j, len;
    if (n > 0u && n <= 512u && (n & (n - 1u)) == 0u) {
        uint32_t shift = 0u, size = n;
        while (size < 512u) { ++shift; size <<= 1u; }
        for (i = 1u; i < n; ++i) {
            j = AP_FFT_BITREV9[i] >> shift;
            if (i < j) {
                ap_complex_t t = x[i]; x[i] = x[j]; x[j] = t;
            }
        }
    } else {
    for (i = 1u, j = 0u; i < n; ++i) {
        uint32_t bit = n >> 1u;
        for (; j & bit; bit >>= 1u) j ^= bit;
        j ^= bit;
        if (i < j) {
            ap_complex_t t = x[i];
            x[i] = x[j];
            x[j] = t;
        }
    }
    }

    if (n <= AP_FFT_TWIDDLE_N && (AP_FFT_TWIDDLE_N % n) == 0u) {
        for (len = 2u; len <= n; len <<= 1u) {
            const uint32_t tw_step = AP_FFT_TWIDDLE_N / len;
            uint32_t base;
            for (base = 0u; base < n; base += len) {
                const uint32_t half = len >> 1u;
                uint32_t k, tw = 0u;
                for (k = 0u; k < half; ++k, tw += tw_step) {
                    const float wr = AP_FFT_TWIDDLE[tw].re;
                    const float wi = inverse ? -AP_FFT_TWIDDLE[tw].im :
                                               AP_FFT_TWIDDLE[tw].im;
                    const ap_complex_t u = x[base + k];
                    const ap_complex_t v0 = x[base + k + half];
                    ap_complex_t v;
                    v.re = v0.re * wr - v0.im * wi;
                    v.im = v0.re * wi + v0.im * wr;
                    x[base + k].re = u.re + v.re;
                    x[base + k].im = u.im + v.im;
                    x[base + k + half].re = u.re - v.re;
                    x[base + k + half].im = u.im - v.im;
                }
            }
        }
    } else {
        /* Generic fallback for future transforms outside the current product
         * geometry. It is intentionally not on the 32/64/256/512 hot paths. */
        for (len = 2u; len <= n; len <<= 1u) {
            const float angle = (inverse ? 2.0f : -2.0f) * AP_PI / (float)len;
            const float wr_step = cosf(angle);
            const float wi_step = sinf(angle);
            uint32_t base;
            for (base = 0u; base < n; base += len) {
                float wr = 1.0f, wi = 0.0f;
                const uint32_t half = len >> 1u;
                uint32_t k;
                for (k = 0u; k < half; ++k) {
                    const ap_complex_t u = x[base + k];
                    const ap_complex_t v0 = x[base + k + half];
                    const float next_wr = wr * wr_step - wi * wi_step;
                    const float next_wi = wr * wi_step + wi * wr_step;
                    ap_complex_t v;
                    v.re = v0.re * wr - v0.im * wi;
                    v.im = v0.re * wi + v0.im * wr;
                    x[base + k].re = u.re + v.re;
                    x[base + k].im = u.im + v.im;
                    x[base + k + half].re = u.re - v.re;
                    x[base + k + half].im = u.im - v.im;
                    wr = next_wr;
                    wi = next_wi;
                }
            }
        }
    }

    if (inverse) {
        const float s = 1.0f / (float)n;
        for (i = 0u; i < n; ++i) {
            x[i].re *= s;
            x[i].im *= s;
        }
    }
}
